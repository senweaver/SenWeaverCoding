// File-icon mapping that powers the right-sidebar workspace tree.
//
// We render via `@iconify/react` against the offline-bundled
// `@iconify-json/vscode-icons` set, which mirrors the VSCode-Icons
// extension's ~1500 colored SVG icons.  Two pieces of state matter:
//
//   • `ensureVscodeIcons()` — lazy-loads the ~3.6 MB `icons.json`
//     into a code-split chunk and registers it with Iconify on first
//     call.  We fire this from `<FileTreeNodeView>` mount so the rest
//     of the app boots without paying for the JSON cost.  Subsequent
//     calls short-circuit.
//
//   • `getFileIconId()` — pure function that maps a filename + dir
//     bit + expanded bit to a Iconify icon id (e.g.
//     `vscode-icons:file-type-typescript`).  All icon ids returned
//     here are *verified* to exist in the bundled pack — the lookup
//     tables below were generated by querying `icons.json` directly,
//     so we never risk handing Iconify a name that resolves to an
//     empty SVG.

import { addCollection, type IconifyJSON } from '@iconify/react/dist/offline'

let registered = false
let registerPromise: Promise<void> | null = null

export function ensureVscodeIcons(): Promise<void> {
  if (registered) return Promise.resolve()
  if (registerPromise) return registerPromise
  registerPromise = import('@iconify-json/vscode-icons/icons.json')
    .then((mod) => {
      const data = ((mod as unknown as { default?: IconifyJSON }).default ??
        (mod as unknown)) as IconifyJSON
      addCollection(data)
      registered = true
    })
    .catch((err) => {

      registerPromise = null
      throw err
    })
  return registerPromise
}

export function isVscodeIconsReady(): boolean {
  return registered
}

