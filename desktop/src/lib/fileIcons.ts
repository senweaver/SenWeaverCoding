export function getFileIconId(
  name: string,
  isDir: boolean,
  expanded: boolean,
): string {
  if (!name) return isDir ? (expanded ? DEFAULT_FOLDER_OPEN : DEFAULT_FOLDER) : DEFAULT_FILE
  const lower = name.toLowerCase()
  if (isDir) {
    const named = FOLDER_NAMED[lower]
    if (named) return `${PREFIX}${named}${expanded ? '-opened' : ''}`
    return expanded ? DEFAULT_FOLDER_OPEN : DEFAULT_FOLDER
  }

  const exact = NAMED[lower]
  if (exact) return `${PREFIX}${exact}`

  if (lower.endsWith('.d.ts')) return `${PREFIX}file-type-typescriptdef`
  if (lower.endsWith('.test.ts') || lower.endsWith('.spec.ts')) {
    return `${PREFIX}file-type-typescript`
  }
  if (lower.endsWith('.test.tsx') || lower.endsWith('.spec.tsx')) {
    return `${PREFIX}file-type-reactts`
  }
  if (lower.endsWith('.test.js') || lower.endsWith('.spec.js')) {
    return `${PREFIX}file-type-js`
  }
  if (lower.endsWith('.stories.ts') || lower.endsWith('.stories.tsx')) {
    return `${PREFIX}file-type-storybook`
  }
  if (lower.endsWith('.module.css')) return `${PREFIX}file-type-css`
  if (lower.endsWith('.module.scss')) return `${PREFIX}file-type-scss`

  const dot = lower.lastIndexOf('.')
  if (dot > 0 && dot < lower.length - 1) {
    const ext = lower.slice(dot + 1)
    const byExt = BY_EXT[ext]
    if (byExt) return `${PREFIX}${byExt}`
  }

  if (lower.startsWith('.')) return `${PREFIX}file-type-text`
  return DEFAULT_FILE
}
